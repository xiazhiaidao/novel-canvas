const assert=require('node:assert/strict');
const {extract,plan}=require('../timeline_sync');
const number=title=>Number(/第(\d+)章/.exec(title)?.[1]) || null;
const text='# 时间线\n\n## 第1章\n- 守住木门\n### 夜间\n- 找到钥匙\n## 资料\n- 不应猜章号\n## 第2章\n| 事件ID | 章节 | 事件 | 时间 | 依据 |\n| --- | --- | --- | --- | --- |\n| door | 2 | 打开木门 | 次日 | 第二段 |\n```\n- 不是真实事件\n```';
const events=extract(text,number);
assert.deepEqual(events.map(e=>e.title),['守住木门','找到钥匙','打开木门']);
assert.equal(events[2].sourceKey,'id:door');
assert.equal(events[2].note,'时间：次日 · 依据：第二段');
assert.throws(()=>extract('## 第1章\n| ID | 事件 |\n| --- | --- |\n| a | 开门 |\n| a | 关门 |',number),/重复/);
assert.equal(extract('## 第一卷\n- 不应当成第一章',number).length,0);
const file='追踪/时间线.md';
const pins=events.map((e,i)=>({...e,id:'tl-'+i,sourceFile:file,sourceChapter:e.chapter,progress:42}));
assert.equal(plan(events,pins,file).length,0);
const revised=[{...events[0],title:'守住第二道门'},events[2]];
const ops=plan(revised,pins,file,1);
assert.deepEqual(ops.map(o=>o.action),['update','delete']);
assert.equal(ops[0].id,'tl-0');
assert.equal(ops[1].id,'tl-1');
assert.equal(plan([events[0]],[{id:'manual',chapter:1,title:'守住木门'}],file).length,0);
assert.equal(plan([],pins,file,1).length,2);
assert.equal(plan([{...events[2],chapter:3}],pins,file,3)[0].id,'tl-2');
console.log('时间线解析验证通过：章节范围、嵌套标题、表格ID与依据、重复ID、代码块、稳定更新、删除预览和手动节点保护。');
